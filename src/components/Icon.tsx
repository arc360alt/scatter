/** Drop-in for FontAwesomeIcon: draws the Hugeicons equivalent in NeoKit mode,
 * the original Font Awesome icon in Classic mode. */
export function Icon(props: FontAwesomeIconProps) {
  const neokit = useSettingsStore((s) => s.uiMode === 'neokit')
  const def = props.icon as IconDefinition
  const huge = neokit && def && typeof def === 'object' ? NEOKIT_ICONS[def.iconName] : undefined
  if (!huge) return <FontAwesomeIcon {...props} />
  const style: CSSProperties = { ...(props.style as CSSProperties) }
  const scale = props.size === 'xs' ? '0.85em' : '1.15em'
  return (
    <HugeiconsIcon
      icon={huge}
      size={scale}
      strokeWidth={1.6}
      className={['nk-icon', props.spin ? 'nk-spin' : '', props.className ?? ''].filter(Boolean).join(' ')}
      style={style}
      aria-hidden
    />
  )
}
